import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const engineFiles = [
  'packages/api/src/journal-rules.js',
  'packages/tuyan-knowledge/src/journals.js',
  'packages/tuyan-knowledge/src/workflows.js',
  'packages/tuyan-knowledge/src/agent-runtime-entry.js',
  'skills/tuyan-scientific-figure/scripts/finalize-output-bundle.mjs',
  'skills/tuyan-scientific-figure/scripts/prepare-knowledge.mjs',
];
const engineHashes = {};
for (const path of engineFiles) engineHashes[path] = createHash('sha256').update(await readFile(resolve(root, path))).digest('hex');
const enginePath = resolve(root, 'packages/tuyan-knowledge/src/engine-fingerprint.js');
const engineText = `// Generated by scripts/sync-agent-knowledge.mjs.\nexport const ENGINE_FINGERPRINT = ${JSON.stringify(engineHashes, null, 2)};\n`;
if (check) {
  if (await readFile(enginePath, 'utf8').catch(() => null) !== engineText) throw new Error('AGENT_ENGINE_DRIFT: regenerate knowledge after workflow/policy/helper changes');
} else await writeFile(enginePath, engineText);
const { createOfflineSnapshot } = await import('../packages/tuyan-knowledge/src/index.js');
const result = await build({
  absWorkingDir: root, entryPoints: ['packages/tuyan-knowledge/src/agent-runtime-entry.js'],
  bundle: true, platform: 'node', format: 'esm', target: 'node24', write: false,
  minifySyntax: true, legalComments: 'none', metafile: true,
  banner: { js: '// Generated by scripts/sync-agent-knowledge.mjs; edit canonical sources, not this file.\nimport { createRequire as __createRequire } from "node:module"; const require = __createRequire(import.meta.url);' },
});
const dependencyRoots = new Set();
for (const path of Object.keys(result.metafile.inputs).filter(path => path.includes('node_modules/'))) {
  let directory = dirname(resolve(root, path));
  while (directory !== root) {
    if (await readFile(resolve(directory, 'package.json'), 'utf8').then(() => true, () => false)) { dependencyRoots.add(directory); break; }
    const parent = dirname(directory);
    if (parent === directory) throw new Error(`Cannot identify bundled dependency: ${path}`);
    directory = parent;
  }
}
const licenses = [];
for (const directory of [...dependencyRoots].sort()) {
  const pkg = JSON.parse(await readFile(resolve(directory, 'package.json'), 'utf8'));
  let license;
  for (const name of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'license.md']) {
    license = await readFile(resolve(directory, name), 'utf8').catch(() => null);
    if (license) break;
  }
  if (!license) throw new Error(`Missing bundled dependency license: ${pkg.name}`);
  licenses.push(`${pkg.name}@${pkg.version} (${pkg.license})\n${license.trim()}`);
}
const outputs = new Map([
  ['skills/tuyan-scientific-figure/scripts/knowledge-runtime.mjs', result.outputFiles[0].text],
  ['skills/tuyan-scientific-figure/references/offline-snapshot.v1.json', `${JSON.stringify(createOfflineSnapshot(), null, 2)}\n`],
  ['skills/tuyan-scientific-figure/references/runtime-licenses.txt', `Third-party licenses for bundled local validation code.\n\n${licenses.join('\n\n-----\n\n')}\n`],
]);
for (const [path, content] of outputs) {
  if (check) {
    if (await readFile(resolve(root, path), 'utf8').catch(() => null) !== content) throw new Error(`AGENT_KNOWLEDGE_DRIFT: ${path}; run node scripts/sync-agent-knowledge.mjs`);
  } else await writeFile(resolve(root, path), content);
}
console.log(check ? 'Agent runtime and complete offline knowledge are synchronized.' : 'Generated Agent runtime and complete offline knowledge.');
