import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
const root=path.resolve(import.meta.dirname,'..'), check=process.argv.includes('--check')
const ts=createRequire(path.join(root,'apps/paperbanana-api/package.json'))('typescript')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
function write(p,s){const file=path.join(root,p);if(check){if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==s)throw Error('Thinking drift: '+p)}else fs.writeFileSync(file,s)}
const dataFiles=['domestic','global'].filter(name=>fs.existsSync(path.join(root,'config/thinking-audit',name+'.json')))
const audits=dataFiles.map(name=>JSON.parse(read('config/thinking-audit/'+name+'.json')))
const rawProfiles=audits.flatMap(audit=>audit.profiles || [])
const runtimeKeys=['id','provider','modelIds','roles','protocols','regions','status','controls','clearFields','checkedAt','operations','transport','exclusiveEffortBudget','requiresBudgetWhenEnabled','budgetRequiresEnabled','invalidCombinations','budgetRelation','budgetOutputField','dropSamplingWhenThinking','dropSamplingOnProviderDefault','dropSamplingAlways','allowEffortWithoutThinking']
const profiles=rawProfiles.map(raw=>{
  const p=Object.fromEntries(runtimeKeys.filter(k=>raw[k]!==undefined).map(k=>[k,raw[k]]))
  const c=raw.constraints && !Array.isArray(raw.constraints) ? raw.constraints : {}
  p.checkedAt ||= '2026-09-22'
  p.budgetRelation ||= c.outputBudgetRelation
  p.dropSamplingWhenThinking ||= Boolean(c.dropSamplingWhenThinking)
  p.dropSamplingAlways ||= Boolean(c.omitSampling)
  p.samplingFields=[...new Set([...(Array.isArray(c.dropSamplingWhenThinking)?c.dropSamplingWhenThinking:[]),...(c.omitSampling||[]),'temperature','top_p','top_k'])]
  p.thinkingCannotDisable=Boolean(c.thinkingCannotDisable)
  p.effortRequiresThinking=Boolean(c.effortRequiresThinking)
  p.budgetRequiresThinking=Boolean(c.budgetRequiresThinking)
  p.disabledEffortValues=c.disabledEffortValues || ['none','off']
  p.requiresNoInputImages=Boolean(c.requiresNoInputImages || raw.provider==='replicate' && raw.modelIds.some(id=>/^wan-video\/wan-2\.7-image/.test(id)))
  p.requiresNonSequentialGeneration=Boolean(c.requiresNonSequentialGeneration || p.requiresNoInputImages)
  p.exclusiveEffortBudget ||= Boolean(c.mutuallyExclusiveFields?.includes('reasoning_effort') || c.exclusiveEffortBudget || c.mutuallyExclusive?.includes('effort') && c.mutuallyExclusive?.includes('budget'))
  p.operations ||= raw.roles.includes('image') ? p.requiresNoInputImages ? ['generation'] : ['generation','editing'] : ['text']
  if (raw.roles.includes('image') && p.operations.includes('generation') && !p.operations.includes('editing')) { p.requiresNoInputImages = true; p.requiresNonSequentialGeneration = true }
  p.transport=p.transport ? {endpointAliases:p.transport.endpointAliases,pinnedSchemaVersion:p.transport.pinnedSchemaVersion} : {}
  p.controls=p.controls.map(control=>{
    const mappings=raw.requestMappings?.find(m=>m.key===control.key)?.providerAliases
    return {...control, ...(control.field==='thinking_strategy'?{label:'思考策略'}:{}), ...(mappings?{providerAliases:mappings}:{})}
  })
  return p
})
const seen=new Set()
for(const p of profiles) for(const model of p.modelIds) for(const role of p.roles) for(const protocol of p.protocols){const key=JSON.stringify([p.provider,model,role,protocol,p.regions]);if(seen.has(key))throw Error('Duplicate thinking identity '+key);seen.add(key)}
const csvRows=[['checked_at','channel','api_model_id','role','protocol','status','parameters','values_or_budget_limits','defaults','operations','constraints','conflicts','notes','official_sources']]
for(const p of rawProfiles)for(const model of p.modelIds)for(const role of p.roles.length?p.roles:['out-of-scope'])for(const protocol of p.protocols)csvRows.push([
  p.checkedAt||'2026-09-22',p.provider,model,role,protocol,p.status,
  p.controls.map(c=>c.field).join(' | '),JSON.stringify(p.controls.map(c=>({key:c.key,...(c.values?{values:c.values}:{min:c.min,max:c.max,allowedSpecialValues:c.allowedSpecialValues})}))),
  JSON.stringify(p.controls.map(c=>({field:c.field,default:c.default}))),JSON.stringify(p.operations||profiles.find(v=>v.id===p.id)?.operations),JSON.stringify(p.constraints),JSON.stringify(p.conflicts),JSON.stringify(p.notes),p.sourceUrls.join(' | '),
])
write('docs/thinking/2026-09-22/support.csv',csvRows.map(row=>row.map(value=>'"'+String(value??'').replaceAll('"','""')+'"').join(',')).join('\n')+'\n')
const data='// Generated by scripts/sync-thinking.mjs. Do not edit.\nexport const THINKING_PROFILES: any[] = '+JSON.stringify(profiles)+'\n'
write('packages/api/src/thinking-data.ts',data)
const types=read('packages/types/src/thinking.ts'), runtime=read('packages/api/src/thinking.ts').replace(/^import .*\n/gm,'')
const combined=types+'\n'+data+'\n'+runtime
write('apps/web/src/lib/thinking.js','// Generated by scripts/sync-thinking.mjs. Do not edit.\n'+ts.transpileModule(combined,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText)
const target='apps/laf-functions/paperbanana-api.ts', start='// BEGIN SHARED THINKING CONFIG',end='// END SHARED THINKING CONFIG'
let backend=read(target)
if(!backend.includes(start))backend=backend.replace('sharp.cache(false)',start+'\n'+end+'\n\nsharp.cache(false)')
backend=backend.slice(0,backend.indexOf(start)+start.length)+'\n'+combined+'\n'+backend.slice(backend.indexOf(end))
write(target,backend)
console.log('Thinking profiles:',profiles.length,check?'no drift':'generated')
