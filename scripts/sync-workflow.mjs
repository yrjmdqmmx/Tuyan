import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
const root = path.resolve(import.meta.dirname, '..')
const ts = createRequire(path.join(root, 'apps/paperbanana-api/package.json'))('typescript')
const check = process.argv.includes('--check')
const source = fs.readFileSync(path.join(root, 'packages/api/src/workflow.ts'), 'utf8')
const banner = '// Generated by scripts/sync-workflow.mjs. Edit packages/api/src/workflow.ts.\n'
const targets = {
  'apps/auth-gateway/src/workflow.js': banner + ts.transpileModule(source, {compilerOptions: {target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022}}).outputText,
  'apps/web/src/lib/workflow.js': banner + ts.transpileModule(source, {compilerOptions: {target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022}}).outputText,
  'apps/miniprogram/miniprogram/utils/workflow.ts': banner + source,
  'apps/miniprogram/miniprogram/utils/workflow.js': ts.transpileModule(banner + source, {compilerOptions: {target: ts.ScriptTarget.ES2019, module: ts.ModuleKind.CommonJS}}).outputText,
}
for (const [file, value] of Object.entries(targets)) {
  if (process.argv.includes('--skip-miniprogram') && file.startsWith('apps/miniprogram/')) continue
  const absolute = path.join(root, file)
  if (check) { if (!fs.existsSync(absolute) || fs.readFileSync(absolute, 'utf8') !== value) throw new Error('Workflow contract drift: '+file) }
  else fs.writeFileSync(absolute, value)
}
console.log('Workflow contract', check ? 'no drift' : 'synchronized')
